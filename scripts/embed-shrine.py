#!/usr/bin/env python3
"""Embed the shrine page and its assets into one TS string.

`test/rest-shrine.html` is the source. The packaged page includes its local
scripts, calligraphy font, and asset notices inline. Run after editing the
page or its assets.
"""
from __future__ import annotations

import base64
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "test" / "rest-shrine.html"
THREE = ROOT / "assets" / "three" / "three.min.js"
FONT = ROOT / "assets" / "fonts" / "shrine-calligraphy.woff"
FONT_LICENSE = FONT.with_name("ZhiMangXing-OFL.txt")
FISH_DIR = ROOT / "assets" / "fish"
SCENE_SCRIPTS = (THREE, FISH_DIR / "room-3d-data.js", FISH_DIR / "model-3d-data.js")
OUT = ROOT / "src" / "shrine-html.ts"


def main() -> int:
    html = SOURCE.read_text(encoding="utf-8")
    font_url = "../" + FONT.relative_to(ROOT).as_posix()
    if font_url not in html:
        raise SystemExit(f"{SOURCE} has no font URL for {FONT.name}")
    font_data = base64.b64encode(FONT.read_bytes()).decode("ascii")
    html = html.replace(font_url, f"data:font/woff;base64,{font_data}", 1)
    license_text = FONT_LICENSE.read_text(encoding="utf-8").rstrip()
    html = html.replace("</head>", f"<!--\n{license_text}\n-->\n</head>", 1)

    fish_notices = "\n\n".join(
        (FISH_DIR / filename).read_text(encoding="utf-8").rstrip()
        for filename in ("NOTICE.md", "YunYueSama-LICENSE.txt")
    )
    html = html.replace("</body>", f"<!--\n{fish_notices}\n-->\n</body>", 1)

    for script in SCENE_SCRIPTS:
        url = "../" + script.relative_to(ROOT).as_posix()
        tag = f'<script src="{url}"></script>'
        if html.count(tag) != 1:
            raise SystemExit(f"{SOURCE} must include {url} exactly once")
        # The packaged WebView loads a string with no filesystem base URL.
        code = re.sub(r"</script", lambda m: "<\\/" + m[0][2:],
                      script.read_text(encoding="utf-8"), flags=re.IGNORECASE)
        html = html.replace(tag, f"<script>\n{code.rstrip()}\n</script>", 1)
    OUT.write_text(
        "// Generated by scripts/embed-shrine.py; edit test/rest-shrine.html instead.\n"
        "// three.js r160, MIT, https://threejs.org\n"
        f"export const SHRINE_HTML = {json.dumps(html, ensure_ascii=False)};\n",
        encoding="utf-8",
    )
    print(f"{OUT.relative_to(ROOT)}: {OUT.stat().st_size} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
