#!/usr/bin/env python3
"""Embed the shrine page and three.js into one TS string.

`test/rest-shrine.html` is the source; `assets/three/three.min.js` is the UMD
build the page expects on `window.THREE`. Run from the repo root after
editing either.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "test" / "rest-shrine.html"
THREE = ROOT / "assets" / "three" / "three.min.js"
OUT = ROOT / "src" / "shrine-html.ts"


def main() -> int:
    html = SOURCE.read_text(encoding="utf-8")
    three = THREE.read_text(encoding="utf-8")

    # The page must not fetch the library: it is injected below.
    html = re.sub(
        r"<script\b[^>]*\bsrc=[\"'][^\"']*three[^\"']*[\"'][^>]*>\s*</script>\s*",
        "",
        html,
        flags=re.IGNORECASE,
    )
    if "<body" not in html.lower():
        raise SystemExit(f"{SOURCE} has no <body>")
    # A page's inline script ends at `</script`; the library may carry one.
    three = three.replace("</script", "<\\/script")
    html = re.sub(
        r"(<body\b[^>]*>)",
        lambda m: m.group(1) + "\n<script>\n" + three + "\n</script>",
        html,
        count=1,
        flags=re.IGNORECASE,
    )
    OUT.write_text(
        "// Generated by scripts/embed-shrine.py; edit test/rest-shrine.html instead.\n"
        "// three.js r160, MIT, https://threejs.org\n"
        f"export const SHRINE_HTML = {json.dumps(html, ensure_ascii=False)};\n",
        encoding="utf-8",
    )
    print(f"{OUT.relative_to(ROOT)}: {OUT.stat().st_size} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
